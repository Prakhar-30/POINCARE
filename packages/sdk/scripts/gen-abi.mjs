// Regenerates src/abi/*.ts from the Foundry build (../../out), so the SDK's ABIs are the
// compiled contracts' ABIs, not hand-copied ones. Run after `forge build` at the repo root:
//   pnpm --dir packages/sdk gen:abi
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, "../../..");
const out = path.join(repo, "out");
const dest = path.resolve(here, "../src/abi");

const abiOf = (file, name) => JSON.parse(fs.readFileSync(path.join(out, file, `${name}.json`), "utf8")).abi;

// The hook's public surface the SDK reads. Liquidity and admin entry points are left out on purpose.
const HOOK_READS = new Set([
  "reserves", "kappa", "trend", "previewSpread", "previewDetector", "effectiveSpread",
  "directionalEfficiency", "sigmaWad", "currentFeeWad", "cusumState", "lastSampledPriceWad",
  "lastSampledBlock", "k", "thresholdH", "sMax", "kappaMin", "kappaMax", "dMax", "lambda",
  "dFloor", "adaptive", "poolKey",
]);

const files = {
  "hook.ts": ["hookAbi", abiOf("PoincareHook.sol", "PoincareHook").filter(
    (x) => (x.type === "function" && HOOK_READS.has(x.name)) || (x.type === "event" && x.name === "DetectorSample"),
  )],
  "lens.ts": ["lensAbi", abiOf("PoincareLens.sol", "PoincareLens").filter((x) => x.type === "function")],
  "dca.ts": ["dcaAbi", abiOf("PoincareDCA.sol", "PoincareDCA").filter((x) => ["function", "event", "error"].includes(x.type))],
};

for (const [file, [name, abi]] of Object.entries(files)) {
  const body = `// Generated by scripts/gen-abi.mjs from the Foundry build. Do not edit by hand.\nexport const ${name} = ${JSON.stringify(abi, null, 2)} as const;\n`;
  fs.writeFileSync(path.join(dest, file), body);
  console.log(`${file}: ${abi.length} entries`);
}
